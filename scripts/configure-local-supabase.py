#!/usr/bin/env python3
"""Write the running local Supabase endpoints to gitignored development env files."""

from __future__ import annotations

import json
import os
from pathlib import Path
import subprocess
import tempfile
import tomllib
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parent.parent
MARKER = "# Local PawPair Supabase stack (generated by supabase status)"
FILES = (
    Path(".env"),
    Path("apps/web/.env"),
    Path("apps/web/.env.local"),
    Path("apps/admin/.env"),
    Path("apps/admin/.env.local"),
    Path("packages/db/.env"),
)


def target_files() -> tuple[Path, ...]:
    active = ROOT / ".project/active.json"
    if not active.is_file():
        return FILES
    selected = json.loads(active.read_text())
    files = [Path(".env")]
    files.extend(Path("apps") / app_id / ".env.local" for app_id in selected["apps"])
    if selected["database"] == "supabase":
        files.append(Path("packages/db/.env"))
    return tuple(files)


def local_status() -> dict[str, str]:
    result = subprocess.run(
        ["supabase", "status", "-o", "json"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    status = json.loads(result.stdout)
    required = {"API_URL", "DB_URL", "ANON_KEY", "SERVICE_ROLE_KEY"}
    if not isinstance(status, dict) or not required.issubset(status):
        raise ValueError("Supabase status did not return the expected local endpoints and keys")

    config = tomllib.loads((ROOT / "supabase/config.toml").read_text())
    for key, port in (("API_URL", config["api"]["port"]), ("DB_URL", config["db"]["port"])):
        url = urlsplit(status[key])
        if url.hostname not in {"127.0.0.1", "localhost"} or url.port != port:
            raise ValueError(f"{key} does not point to this repository's local stack")
    return status


def update_file(path: Path, values: dict[str, str]) -> None:
    original = path.read_text() if path.exists() else ""
    kept = []
    for line in original.splitlines():
        key = line.split("=", 1)[0].strip() if "=" in line and not line.lstrip().startswith("#") else None
        if key not in values and line != MARKER:
            kept.append(line)
    kept.append(MARKER)
    kept.extend(f"{key}={json.dumps(value)}" for key, value in values.items())
    content = "\n".join(kept).rstrip() + "\n"

    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temp_path = tempfile.mkstemp(prefix=".pawpair-env-", dir=path.parent)
    try:
        with os.fdopen(handle, "w") as output:
            output.write(content)
            output.flush()
            os.fsync(output.fileno())
        os.chmod(temp_path, 0o600)
        os.replace(temp_path, path)
    finally:
        if os.path.exists(temp_path):
            os.unlink(temp_path)


def main() -> None:
    status = local_status()
    db_url = status["DB_URL"]
    shared = {
        "NEXT_PUBLIC_SUPABASE_URL": status["API_URL"],
        "NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY": status["ANON_KEY"],
        "NEXT_PUBLIC_SUPABASE_ANON_KEY": status["ANON_KEY"],
        "DATABASE_URL": db_url,
        "DIRECT_URL": db_url,
        "DATABASE_PASSWORD": unquote(urlsplit(db_url).password or ""),
    }
    for relative_path in target_files():
        values = dict(shared)
        if not (ROOT / ".project/active.json").is_file() and relative_path.parts[:2] == ("apps", "admin"):
            values["SUPABASE_SERVICE_ROLE_KEY"] = status["SERVICE_ROLE_KEY"]
        update_file(ROOT / relative_path, values)
        print(f"Updated {relative_path} for the local Supabase stack")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.CalledProcessError, json.JSONDecodeError) as error:
        raise SystemExit(f"Local Supabase setup failed: {type(error).__name__}") from error
